"""Client interface for Google Gemini API structured inference."""

import json
from typing import Any, List, Optional, Type
from google import genai
from google.genai import types
from pydantic import BaseModel
from app.config import get_settings


class GeminiClient:
    """Wrapper for calling Google Gemini models with structured schema constraints."""

    def __init__(self, api_key: Optional[str] = None, model_name: Optional[str] = None):
        """Initialize the Gemini client.

        Args:
            api_key: Optional API key override. If not provided, loaded from Settings.
            model_name: Optional model override (defaults to gemini-2.5-flash).
        """
        settings = get_settings()
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.model_name = model_name or settings.GEMINI_MODEL_NAME

        if not self.api_key:
            self._client = None
        else:
            self._client = genai.Client(api_key=self.api_key)

    @property
    def is_configured(self) -> bool:
        """Return True if a valid Gemini API key is configured."""
        return self._client is not None

    def generate(
        self,
        contents: List[Any],
        schema: Optional[Type[BaseModel]] = None,
        system_instruction: Optional[str] = None,
    ) -> str:
        """Execute a content generation request to Gemini with JSON schema enforcement.

        Args:
            contents: List of message strings or parts representing conversation turns.
            schema: Optional Pydantic model to enforce structured output.
            system_instruction: Optional system instruction prompt.

        Returns:
            The raw string response generated by the model.

        Raises:
            ValueError: If Gemini API key is missing.
            RuntimeError: If the Gemini API request fails.
        """
        if not self._client:
            raise ValueError(
                "Gemini API key is not configured. Please set GEMINI_API_KEY in your environment or .env file."
            )

        config_args: dict = {
            "response_mime_type": "application/json",
            "temperature": 0.1,  # Low temperature for deterministic, factual parsing
        }

        if schema is not None:
            config_args["response_schema"] = schema

        if system_instruction is not None:
            config_args["system_instruction"] = system_instruction

        config = types.GenerateContentConfig(**config_args)

        try:
            response = self._client.models.generate_content(
                model=self.model_name,
                contents=contents,
                config=config,
            )
            return response.text or "{}"
        except Exception as e:
            raise RuntimeError(f"Gemini API generation error: {str(e)}") from e
